const prompt = require('prompt-sync')({sigint: true})
let nilai = Number(prompt('masukkan nilai (0-100): '))
if (nilai >= 90 && nilai <= 100)
    console.log(`predikat : A`)
else if (nilai >= 80 && nilai < 90)
    console.log(`predikat : B`)
else if (nilai >= 75 && nilai < 80)
    console.log(`predikat : C`)
else if (nilai >= 60 && nilai < 75)
    console.log(`predikat : D`)
else if (nilai >= 45 && nilai < 60)
    console.log(`predikat : E`)
else if (nilai >= 0 && nilai < 45)
    console.log(`predikat : F`)